export function getServiceBySlug(slug: string): ServiceCategory | undefined {
  return serviceCategories.find((category) => category.slug === slug);
}

export function getStartingPrice(category: ServiceCategory): string {
  const amounts = category.items
    .map((item) => Number(item.price.replace(/[^\d]/g, '')))
    .filter((value) => !Number.isNaN(value) && value > 0);

  if (!amounts.length) return category.items[0]?.price ?? '';
  return `від ${Math.min(...amounts)} ₴`;
}
